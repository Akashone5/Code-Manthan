DROP POLICY IF EXISTS "Users can view own profile or officers view all" ON public.profiles;
CREATE POLICY "Users can view own profile or officers view all"
ON public.profiles
FOR SELECT
USING (
    auth.uid() = id
    OR public.is_officer()
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile"
ON public.profiles
FOR UPDATE
USING (
    auth.uid() = id
    OR public.is_officer()
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Enable insert for auth system or users" ON public.profiles;
CREATE POLICY "Enable insert for auth system or users"
ON public.profiles
FOR INSERT
WITH CHECK (
    auth.uid() = id 
    OR auth.role() IN ('anon', 'authenticated', 'service_role')
);

DROP POLICY IF EXISTS "Applicants view own applications, officers view all" ON public.loan_applications;
CREATE POLICY "Applicants view own applications, officers view all"
ON public.loan_applications
FOR SELECT
USING (
    auth.uid() = user_id 
    OR auth.uid() = applicant_id 
    OR LOWER(applicant_email) = LOWER(COALESCE(auth.jwt()->>'email', ''))
    OR public.is_officer()
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Applicants can insert their own application" ON public.loan_applications;
CREATE POLICY "Applicants can insert their own application"
ON public.loan_applications
FOR INSERT
WITH CHECK (
    auth.uid() = user_id 
    OR auth.uid() = applicant_id
    OR public.is_officer()
    OR auth.role() = 'service_role'
);

