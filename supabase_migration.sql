-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Create the profiles Table
-- Links 1-to-1 with Supabase Auth (auth.users.id)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    role TEXT NOT NULL DEFAULT 'applicant' CHECK (role IN ('applicant', 'officer')),
    officer_code TEXT,
    is_verified_officer BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 3. Create the loan_applications Table
CREATE TABLE IF NOT EXISTS public.loan_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    application_no TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    phone TEXT,
    gender TEXT NOT NULL,
    marital_status TEXT NOT NULL,
    dependents TEXT NOT NULL,
    education TEXT NOT NULL,
    employment_type TEXT NOT NULL,
    salary_slip TEXT DEFAULT 'Yes',
    applicant_income NUMERIC NOT NULL,
    coapplicant_income NUMERIC NOT NULL,
    loan_amount NUMERIC NOT NULL,
    loan_term_months INTEGER NOT NULL,
    cibil_score INTEGER NOT NULL,
    credit_history INTEGER NOT NULL,
    property_area TEXT NOT NULL,
    loan_purpose TEXT NOT NULL,
    approval_likelihood INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'Conditional',
    monthly_emi NUMERIC NOT NULL,
    dti_percent NUMERIC NOT NULL,
    explanation_summary TEXT,
    positive_factors_json JSONB DEFAULT '[]'::jsonb,
    risk_factors_json JSONB DEFAULT '[]'::jsonb,
    recommendations_json JSONB DEFAULT '[]'::jsonb,
    officer_status TEXT DEFAULT 'Pending' CHECK (officer_status IN ('Pending', 'Approved', 'Conditional', 'Rejected')),
    officer_remarks TEXT,
    officer_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 4. Create Performance & Query Indexes
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);
CREATE INDEX IF NOT EXISTS idx_profiles_role ON public.profiles(role);
CREATE INDEX IF NOT EXISTS idx_loan_app_user_id ON public.loan_applications(user_id);
CREATE INDEX IF NOT EXISTS idx_loan_app_applicant_id ON public.loan_applications(applicant_id);
CREATE INDEX IF NOT EXISTS idx_loan_app_status ON public.loan_applications(status);
CREATE INDEX IF NOT EXISTS idx_loan_app_created ON public.loan_applications(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_loan_app_no ON public.loan_applications(application_no);

-- 5. Helper Function: Check if current authenticated user is a verified Loan Officer
CREATE OR REPLACE FUNCTION public.is_officer()
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role = 'officer'
    );
$$;

-- 6. Trigger to automatically provision public.profiles upon auth.users signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    assigned_role TEXT;
    officer_key TEXT;
    is_verified BOOLEAN;
BEGIN
    assigned_role := COALESCE(new.raw_user_meta_data->>'role', 'applicant');
    officer_key := new.raw_user_meta_data->>'officer_key';
    
    -- Verify officer authorization passkey
    IF assigned_role = 'officer' THEN
        IF officer_key = 'OFFICER-2026' OR officer_key = 'MERIDIAN-ADMIN' THEN
            is_verified := TRUE;
        ELSE
            assigned_role := 'applicant';
            is_verified := FALSE;
        END IF;
    ELSE
        is_verified := FALSE;
    END IF;

    INSERT INTO public.profiles (
        id,
        full_name,
        email,
        phone,
        role,
        is_verified_officer,
        created_at,
        updated_at
    )
    VALUES (
        new.id,
        COALESCE(new.raw_user_meta_data->>'full_name', 'Applicant'),
        new.email,
        new.raw_user_meta_data->>'phone',
        assigned_role,
        is_verified,
        NOW(),
        NOW()
    )
    ON CONFLICT (id) DO UPDATE
    SET full_name = EXCLUDED.full_name,
        phone = EXCLUDED.phone,
        role = EXCLUDED.role,
        updated_at = NOW();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 7. Enable Row Level Security (RLS) on both tables
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loan_applications ENABLE ROW LEVEL SECURITY;

-- 8. Row Level Security Policies for profiles Table
DROP POLICY IF EXISTS "Users can view own profile or officers view all" ON public.profiles;
CREATE POLICY "Users can view own profile or officers view all"
ON public.profiles
FOR SELECT
USING (
    auth.uid() = id
    OR public.is_officer()
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile"
ON public.profiles
FOR UPDATE
USING (
    auth.uid() = id
    OR public.is_officer()
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Enable insert for auth system or users" ON public.profiles;
CREATE POLICY "Enable insert for auth system or users"
ON public.profiles
FOR INSERT
WITH CHECK (
    auth.uid() = id 
    OR auth.role() IN ('anon', 'authenticated', 'service_role')
);

-- 9. Row Level Security Policies for loan_applications Table
DROP POLICY IF EXISTS "Applicants view own applications, officers view all" ON public.loan_applications;
CREATE POLICY "Applicants view own applications, officers view all"
ON public.loan_applications
FOR SELECT
USING (
    auth.uid() = user_id 
    OR auth.uid() = applicant_id 
    OR public.is_officer()
    OR user_id IS NULL
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Applicants can insert their own application" ON public.loan_applications;
CREATE POLICY "Applicants can insert their own application"
ON public.loan_applications
FOR INSERT
WITH CHECK (
    auth.uid() = user_id 
    OR auth.uid() = applicant_id
    OR user_id IS NULL
    OR auth.role() IN ('anon', 'authenticated', 'service_role')
);

DROP POLICY IF EXISTS "Only officers can update loan application status and remarks" ON public.loan_applications;
CREATE POLICY "Only officers can update loan application status and remarks"
ON public.loan_applications
FOR UPDATE
USING (
    public.is_officer()
    OR auth.uid() = user_id
    OR auth.role() = 'service_role'
);

-- 10. Grant Grants & Privileges to API Roles
GRANT ALL ON public.profiles TO anon, authenticated, service_role;
GRANT ALL ON public.loan_applications TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
