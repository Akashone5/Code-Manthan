CREATE OR REPLACE FUNCTION public.is_officer()
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role = 'officer'
    );
$$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    assigned_role TEXT;
    officer_key TEXT;
    is_verified BOOLEAN;
BEGIN
    assigned_role := COALESCE(new.raw_user_meta_data->>'role', 'applicant');
    officer_key := new.raw_user_meta_data->>'officer_key';
    
    IF assigned_role = 'officer' THEN
        IF officer_key = 'REPLACE-WITH-STRONG-OFFICER-KEY' THEN
            is_verified := TRUE;
        ELSE
            assigned_role := 'applicant';
            is_verified := FALSE;
        END IF;
    ELSE
        is_verified := FALSE;
    END IF;

    INSERT INTO public.profiles (
        id,
        full_name,
        email,
        phone,
        role,
        is_verified_officer,
        created_at,
        updated_at
    )
    VALUES (
        new.id,
        COALESCE(new.raw_user_meta_data->>'full_name', 'Applicant'),
        new.email,
        new.raw_user_meta_data->>'phone',
        assigned_role,
        is_verified,
        NOW(),
        NOW()
    )
    ON CONFLICT (id) DO UPDATE
    SET full_name = EXCLUDED.full_name,
        phone = EXCLUDED.phone,
        role = EXCLUDED.role,
        updated_at = NOW();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

