CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    role TEXT NOT NULL DEFAULT 'applicant' CHECK (role IN ('applicant', 'officer')),
    officer_code TEXT,
    is_verified_officer BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE TABLE IF NOT EXISTS public.loan_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    applicant_email TEXT,
    application_no TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    phone TEXT,
    gender TEXT NOT NULL,
    marital_status TEXT NOT NULL,
    dependents TEXT NOT NULL,
    education TEXT NOT NULL,
    employment_type TEXT NOT NULL,
    salary_slip TEXT DEFAULT 'Yes',
    applicant_income NUMERIC NOT NULL,
    coapplicant_income NUMERIC NOT NULL,
    loan_amount NUMERIC NOT NULL,
    loan_term_months INTEGER NOT NULL,
    cibil_score INTEGER NOT NULL,
    credit_history INTEGER NOT NULL,
    property_area TEXT NOT NULL,
    loan_purpose TEXT NOT NULL,
    approval_likelihood INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'Conditional',
    monthly_emi NUMERIC NOT NULL,
    dti_percent NUMERIC NOT NULL,
    explanation_summary TEXT,
    positive_factors_json JSONB DEFAULT '[]'::jsonb,
    risk_factors_json JSONB DEFAULT '[]'::jsonb,
    recommendations_json JSONB DEFAULT '[]'::jsonb,
    officer_status TEXT DEFAULT 'Pending' CHECK (officer_status IN ('Pending', 'Approved', 'Conditional', 'Rejected')),
    officer_remarks TEXT,
    officer_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

ALTER TABLE public.loan_applications ADD COLUMN IF NOT EXISTS applicant_email TEXT;
ALTER TABLE public.loan_applications ADD COLUMN IF NOT EXISTS email_otp_verified BOOLEAN DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.email_otps (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL,
    purpose TEXT NOT NULL CHECK (purpose IN ('signup', 'forgot_password', 'application')),
    otp_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    attempts_left INTEGER NOT NULL DEFAULT 5,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    verified_at TIMESTAMPTZ,
    verification_token TEXT,
    token_expires_at TIMESTAMPTZ,
    token_consumed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.system_settings (
    setting_key TEXT PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_by TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    officer_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    officer_name TEXT NOT NULL,
    officer_role TEXT DEFAULT 'officer',
    application_no TEXT NOT NULL,
